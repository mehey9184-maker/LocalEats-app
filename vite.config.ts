import tailwindcss from '@tailwindcss/vite';
import react from '@vitejs/plugin-react';
import path from 'path';
import {execFileSync} from 'node:child_process';
import {defineConfig, loadEnv} from 'vite';
import { VitePWA } from 'vite-plugin-pwa';

export default defineConfig(({mode,command}) => {
  const env = loadEnv(mode, '.', '');
  // The staging worker has its own Firebase project. Vercel may invoke
  // "vite build" directly rather than package.json's npm build script.
  // Validate before bundling, then rewrite the emitted (not tracked) worker.
  const isolatedWorkerBuild=command === 'build' && env.LOCALEATS_STAGING_ONLY === 'true';
  const runIsolatedWorkerTool=(flag:'--check'|'--inject')=>{
    execFileSync(process.execPath, ['scripts/l3-n2-staging-fcm.mjs',flag], {
      cwd:process.cwd(),
      env:{...process.env,...env},
      stdio:'inherit'
    });
  };
  if(isolatedWorkerBuild)runIsolatedWorkerTool('--check');
  // This URL is generated by Vercel for the exact Preview build; it avoids
  // enabling staging push on some other project's Preview origin.
  // The prebuild validation separately rejects unexpected staging hostnames.
  const stagingPushOrigin = env.LOCALEATS_STAGING_ONLY === "true" &&
    env.VERCEL_ENV === "preview" && env.VERCEL_URL
    ? "https://" + env.VERCEL_URL
    : env.VITE_CUSTOMER_PUSH_STAGING_ORIGIN || "";
  // L3-N3: Preview-only pairing for the isolated Customer notification-test
  // branch. A draft-only build uses the corresponding API branch alias;
  // other previews and Production keep their existing configured API URL.
  const l3n3IsolatedPreview =
    env.LOCALEATS_STAGING_ONLY === "true" &&
    env.VERCEL_ENV === "preview" &&
    env.VERCEL_GIT_COMMIT_REF === "review/l3-n3-customer-api-pairing" &&
    env.VITE_FIREBASE_PROJECT_ID === "localeats-staging" &&
    env.VITE_PICKUP_ORDERING_ENABLED === "false";
  const stagedApiOrigin = l3n3IsolatedPreview
    ? "https://localeats-api-staging-r52d-git-112955-mehey9184-makers-projects.vercel.app"
    : env.VITE_LOCALEATS_API_URL || "";
  return {
    plugins: [
      react(),
      tailwindcss(),
      VitePWA({
        strategies: 'injectManifest',
        srcDir: 'src',
        filename: 'sw.ts',
        registerType: 'autoUpdate',
        injectRegister: 'inline',
        injectManifest: {
          maximumFileSizeToCacheInBytes: 6000000,
        },
        manifest: {
          short_name: "LocalEats",
          name: "LocalEats | Local's Best Kota & Braai",
          icons: [
            {
              src: "/logo.png?v=2",
              type: "image/png",
              sizes: "192x192"
            },
            {
              src: "/logo.png?v=2",
              type: "image/png",
              sizes: "512x512"
            }
          ],
          start_url: ".",
          display: "standalone",
          theme_color: "#FF6B00",
          background_color: "#ffffff"
        },
        devOptions: {
          enabled: false,
          type: 'module'
        }
      }),
      {
        name:'localeats-isolated-fcm-worker-parity',
        apply:'build' as const,
        enforce:'post' as const,
        // Vite has copied public/firebase-messaging-sw.js into dist by
        // this point, even when invoked outside "npm run build".
        closeBundle() {
          if(isolatedWorkerBuild)runIsolatedWorkerTool('--inject');
        }
      }
    ],
    define: {
      'process.env.GEMINI_API_KEY': JSON.stringify(env.GEMINI_API_KEY),
      'import.meta.env.VITE_CUSTOMER_PUSH_STAGING_ORIGIN': JSON.stringify(stagingPushOrigin),
      'import.meta.env.VITE_LOCALEATS_API_URL': JSON.stringify(stagedApiOrigin),
    },
    resolve: {
      alias: {
        '@': path.resolve(__dirname, '.'),
      },
      dedupe: ['react', 'react-dom'],
    },
    server: {
      // HMR is disabled in AI Studio via DISABLE_HMR env var.
      // Do not modifyâfile watching is disabled to prevent flickering during agent edits.
      hmr: process.env.DISABLE_HMR !== 'true',
    },
  };
});
